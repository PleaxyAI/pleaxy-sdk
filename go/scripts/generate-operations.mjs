#!/usr/bin/env node
// Writes operations.gen.go: one method on *Client per operation, named after its
// operationId (CreatePurchaseOrder), that calls oapi-codegen's
// <Op>WithResponse, turns a non-2xx status into an *Error, and returns the
// success body (or the raw bytes of a file download).
//
// It also renames oapi-codegen's NewClient in pleaxy.gen.go to newRawClient,
// so pleaxy.NewClient is this package's own constructor (client.go).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(resolve(here, "../openapi/pleaxy.json"), "utf8"));
const generatedPath = resolve(here, "pleaxy.gen.go");
const generated = readFileSync(generatedPath, "utf8").replace(/\bNewClient\(/g, "newRawClient(").replace(/^\/\/ NewClient /m, "// newRawClient ");
writeFileSync(generatedPath, generated);

// The signature oapi-codegen gave <Op>WithResponse, minus ctx and reqEditors.
function withResponseParams(id) {
  const match = new RegExp(`func \\(c \\*ClientWithResponses\\) ${id}WithResponse\\(ctx context\\.Context, ?(.*?),? ?reqEditors \\.\\.\\.RequestEditorFn\\)`).exec(generated);
  if (!match) throw new Error(`No ${id}WithResponse in pleaxy.gen.go`);
  return match[1].trim().replace(/,$/, "");
}

// The Go type of <Op>Response.JSON<code>.
function responseFieldType(id, code) {
  const struct = new RegExp(`type ${id}Response struct \\{([\\s\\S]*?)\\n\\}`).exec(generated);
  if (!struct) throw new Error(`No ${id}Response in pleaxy.gen.go`);
  const field = new RegExp(`JSON${code}[ \\t]+([^\\n]+)`).exec(struct[1]);
  return field?.[1].trim();
}

const comment = (text) =>
  text
    ? text
        .split("\n")
        .map((l) => `// ${l}`.trimEnd())
        .join("\n") + "\n"
    : "";

let out = `// Code generated by scripts/generate-operations.mjs from openapi/pleaxy.json; DO NOT EDIT.

package pleaxy

import "context"

`;
const ops = Object.values(spec.paths)
  .flatMap((item) => Object.values(item))
  .sort((a, b) => a.operationId.localeCompare(b.operationId));
for (const op of ops) {
  const id = op.operationId;
  const params = withResponseParams(id);
  const args = params ? params.split(/,\s*/).map((p) => p.split(" ")[0]) : [];
  const [code, success] = Object.entries(op.responses).find(([c]) => c.startsWith("2"));
  const binary = success.content && !success.content["application/json"];
  const jsonType = success.content?.["application/json"] ? responseFieldType(id, code) : undefined;
  if (success.content?.["application/json"] && !jsonType) throw new Error(`${id}: no JSON${code} field`);

  const doc = [`${id} - ${op.summary ?? ""}`.trim(), op.description].filter(Boolean).join("\n\n");
  out += comment(doc);
  const signature = `func (c *Client) ${id}(ctx context.Context${params ? ", " + params : ""})`;
  const call = `c.api.${id}WithResponse(ctx${args.length ? ", " + args.join(", ") : ""})`;
  if (binary) {
    out += `${signature} ([]byte, error) {\n\tresp, err := ${call}\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tif err := checkStatus(resp.HTTPResponse, resp.Body); err != nil {\n\t\treturn nil, err\n\t}\n\treturn resp.Body, nil\n}\n\n`;
  } else if (jsonType) {
    out += `${signature} (${jsonType}, error) {\n\tresp, err := ${call}\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tif err := checkStatus(resp.HTTPResponse, resp.Body); err != nil {\n\t\treturn nil, err\n\t}\n\treturn resp.JSON${code}, nil\n}\n\n`;
  } else {
    out += `${signature} error {\n\tresp, err := ${call}\n\tif err != nil {\n\t\treturn err\n\t}\n\treturn checkStatus(resp.HTTPResponse, resp.Body)\n}\n\n`;
  }
}
writeFileSync(resolve(here, "operations.gen.go"), out.trimEnd() + "\n");
console.log(`operations.gen.go: ${ops.length} operations`);
