"""Writes src/pleaxy/_resources.py: one class per API tag with one method per
operation, named after its operationId (CreatePurchaseOrder ->
create_purchase_order), with the same arguments and types as the generated
`sync_detailed` function minus `client`.

Each method builds its request with the generated module's `_get_kwargs` and
parses the answer with its `_parse_response`; the client sends it, raises
PleaxyError for a non-2xx status, and returns file downloads as bytes.

Usage: python scripts/generate_resources.py
"""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT.parent / "openapi" / "pleaxy.json").read_text())
GENERATED = ROOT / "src" / "pleaxy" / "_generated"


def snake(name: str) -> str:
    name = re.sub(r"[-\s]+", "_", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-_\s]+", name))


def signature(module_file: Path) -> tuple[list[str], list[str], str]:
    """(parameters for the facade method, names to pass through, return annotation) of `sync_detailed`."""
    tree = ast.parse(module_file.read_text())
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "sync_detailed")
    params: list[str] = []
    names: list[str] = []
    for arg in fn.args.args:
        params.append(f"{arg.arg}: {ast.unparse(arg.annotation)}")
        names.append(arg.arg)
    kwonly = []
    for arg, default in zip(fn.args.kwonlyargs, fn.args.kw_defaults):
        if arg.arg == "client":
            continue
        text = f"{arg.arg}: {ast.unparse(arg.annotation)}"
        if default is not None:
            text += f" = {ast.unparse(default)}"
        kwonly.append(text)
        names.append(arg.arg)
    if kwonly:
        params.append("*")
        params.extend(kwonly)
    returns = ast.unparse(fn.returns)
    inner = re.fullmatch(r"Response\[(.*)\]", returns)
    return params, names, inner.group(1) if inner else "Any"


def docstring(op: dict) -> str:
    text = "\n\n".join(t for t in (op.get("summary"), op.get("description")) if t).replace('"""', "'''").replace("\\", "\\\\")
    return f'        """{text}"""\n' if text else ""


def main() -> None:
    groups: dict[str, list[tuple[str, dict]]] = {}
    for path, item in SPEC["paths"].items():
        for method, op in item.items():
            groups.setdefault(op["tags"][0], []).append((path, op))

    out = [
        "# Generated by scripts/generate_resources.py from openapi/pleaxy.json - do not edit.",
        "# ruff: noqa: F401, F403, F405, E501",
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Any, Dict, List, Optional, Union",
        "",
        "from ._generated.models import *",
        "from ._generated.types import UNSET, File, Unset",
        "",
        "if TYPE_CHECKING:",
        "    from ._transport import Transport",
        "",
    ]
    resources: list[tuple[str, str]] = []
    for tag in sorted(groups):
        tag_module = snake(tag)
        class_name = f"{pascal(tag)}Resource"
        resources.append((tag_module, class_name))
        out += ["", f"class {class_name}:", "    def __init__(self, transport: Transport) -> None:", "        self._transport = transport", ""]
        for path, op in sorted(groups[tag], key=lambda p: p[1]["operationId"]):
            name = snake(op["operationId"])
            module = f"pleaxy._generated.api.{tag_module}.{name}"
            module_file = GENERATED / "api" / tag_module / f"{name}.py"
            params, names, returns = signature(module_file)
            success = next((r for code, r in op["responses"].items() if code.startswith("2")), {})
            binary = bool(success.get("content")) and "application/json" not in success["content"]
            if binary:
                returns = "bytes"
            elif not success.get("content"):
                returns = "None"
            args = ", ".join(["self", *params])
            call_args = ", ".join(f"{n}={n}" for n in names)
            out.append(f"    def {name}({args}) -> {returns}:")
            out.append(docstring(op).rstrip("\n")) if docstring(op) else None
            out.append(f'        return self._transport.call("{module}"{", binary=True" if binary else ""}{", " + call_args if call_args else ""})')
            out.append("")

    out += ["", "class Resources:", '    """Every resource, one per API area."""', "", "    def __init__(self, transport: Transport) -> None:"]
    for prop, class_name in resources:
        out.append(f"        self.{prop} = {class_name}(transport)")
    out.append("")

    target = ROOT / "src" / "pleaxy" / "_resources.py"
    target.write_text("\n".join(line for line in out if line is not None))
    print(f"{target.relative_to(ROOT)}: {len(resources)} resources, {sum(len(v) for v in groups.values())} operations")


if __name__ == "__main__":
    main()
