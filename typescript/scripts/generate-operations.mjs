#!/usr/bin/env node
// Writes src/operations.ts: one class per API tag (purchaseOrders, invoices, ...)
// with one method per operation, named after its operationId
// (CreatePurchaseOrder -> createPurchaseOrder). Arguments: the path parameters
// in path order, then the JSON body (when the operation takes one), then the
// query parameters (when it has any), then per-call options.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(resolve(here, "../../openapi/pleaxy.json"), "utf8"));

const camel = (s) => s.replace(/[-_ ]+(\w)/g, (_, c) => c.toUpperCase()).replace(/^\w/, (c) => c.toLowerCase());
const pascal = (s) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const comment = (text, indent) => {
  if (!text) return "";
  const lines = text.replace(/\*\//g, "*\\/").split("\n");
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`;
};

const groups = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const tag = op.tags?.[0] ?? "default";
    if (!groups.has(tag)) groups.set(tag, []);
    groups.get(tag).push({ path, method, op });
  }
}

let out = `// Generated by scripts/generate-operations.mjs from openapi/pleaxy.json - do not edit.
import type { Transport, RequestOptions, RequestBody, QueryParams, ResponseBody } from "./transport.js";

`;
const resources = [];
for (const [tag, ops] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  const className = `${pascal(tag)}Resource`;
  resources.push({ prop: camel(tag), className });
  out += `export class ${className} {\n  constructor(private readonly transport: Transport) {}\n`;
  for (const { path, method, op } of ops.sort((a, b) => a.op.operationId.localeCompare(b.op.operationId))) {
    const id = op.operationId;
    const pathParams = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const query = (op.parameters ?? []).filter((p) => p.in === "query");
    const hasBody = !!op.requestBody?.content?.["application/json"];
    const bodyRequired = hasBody && op.requestBody.required !== false;
    const queryRequired = query.some((p) => p.required);
    const success = Object.entries(op.responses ?? {}).find(([code]) => code.startsWith("2"))?.[1];
    const binary = success?.content && !success.content["application/json"];

    const args = pathParams.map((p) => `${p}: string`);
    if (hasBody) args.push(`body${bodyRequired ? "" : "?"}: RequestBody<"${id}">`);
    if (query.length) args.push(`query${queryRequired ? "" : "?"}: QueryParams<"${id}">`);
    args.push("options?: RequestOptions");
    const returns = binary ? "ArrayBuffer" : `ResponseBody<"${id}">`;
    const pathArg = pathParams.length ? `{ ${pathParams.join(", ")} }` : "undefined";

    out += "\n" + comment([op.summary, op.description].filter(Boolean).join("\n\n"), "  ");
    out += `  ${camel(id)}(${args.join(", ")}): Promise<${returns}> {\n`;
    out += `    return this.transport.request("${method}", "${path}", { path: ${pathArg}, ${query.length ? "query, " : ""}${hasBody ? "body, " : ""}${binary ? 'parseAs: "arrayBuffer", ' : ""}options }) as Promise<${returns}>;\n  }\n`;
  }
  out += "}\n\n";
}

out += `/** Every resource, one per API area. */\nexport class Resources {\n`;
for (const { prop, className } of resources) out += `  readonly ${prop}: ${className};\n`;
out += `\n  constructor(transport: Transport) {\n`;
for (const { prop, className } of resources) out += `    this.${prop} = new ${className}(transport);\n`;
out += `  }\n}\n`;

writeFileSync(resolve(here, "../src/operations.ts"), out);
console.log(`src/operations.ts: ${resources.length} resources, ${[...groups.values()].flat().length} operations`);
