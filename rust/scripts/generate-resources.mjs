#!/usr/bin/env node
// Writes src/resources.rs: one struct per API area (PurchaseOrders, Invoices, ...)
// reached from Client (client.purchase_orders()), with one async method per
// operation that calls the generated function in src/apis with the client's
// configuration - the same arguments minus `configuration`. A file download
// (CSV, PDF) returns its bytes: the generated function would parse it as JSON.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(resolve(root, "../openapi/pleaxy.json"), "utf8"));
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
// fn name -> { method, path, query } for operations whose success body is a file, not JSON.
const downloads = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const success = Object.entries(op.responses).find(([c]) => c.startsWith("2"))?.[1];
    if (success?.content && !success.content["application/json"]) {
      downloads.set(snake(op.operationId), { method: method.toUpperCase(), path, query: (op.parameters ?? []).filter((p) => p.in === "query").map((p) => p.name) });
    }
  }
}
const apisDir = resolve(root, "src/apis");
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

let structs = "";
let accessors = "";
let count = 0;
for (const file of readdirSync(apisDir).filter((f) => f.endsWith("_api.rs")).sort()) {
  const module = file.replace(/\.rs$/, "");
  const area = module.replace(/_api$/, "");
  const name = pascal(area);
  const source = readFileSync(resolve(apisDir, file), "utf8");
  const fns = [...source.matchAll(/((?:^\/\/\/[^\n]*\n)*)pub async fn (\w+)\(configuration: &configuration::Configuration(?:, )?([^)]*)\) -> (Result<[^{]+>) \{/gm)];
  if (!fns.length) throw new Error(`no functions in ${file}`);
  structs += `/// ${name} operations: \`client.${area}()\`.\n#[derive(Debug, Clone, Copy)]\npub struct ${name}<'a>(&'a Client);\n\nimpl<'a> ${name}<'a> {\n`;
  for (const [, doc, fn, params, ret] of fns) {
    const args = params ? params.split(/,\s*(?=\w+:)/).map((p) => p.split(":")[0].trim()) : [];
    const typed = ret.replace(/\bmodels::/g, "crate::models::").replace(/Error<(\w+)>/, `crate::apis::Error<crate::apis::${module}::$1>`);
    const typedParams = params.replace(/\bmodels::/g, "crate::models::");
    const docs = doc.replace(/^\/\/\//gm, "    ///");
    const download = downloads.get(fn);
    if (download) {
      const errorType = /Error<(\w+)>/.exec(ret)[1];
      let path = JSON.stringify(download.path);
      for (const name of download.path.match(/\{(\w+)\}/g) ?? []) {
        const arg = snake(name.slice(1, -1));
        path = `${path}.replace("${name}", &crate::apis::urlencode(${arg}))`;
      }
      const query = download.query.map((q) => `("${q}", ${snake(q)})`).join(", ");
      // The one argument that's neither a path nor a query parameter is the request body (an export's { invoiceIds }).
      const named = new Set([...(download.path.match(/\{(\w+)\}/g) ?? []).map((n) => snake(n.slice(1, -1))), ...download.query.map(snake)]);
      const bodyParam = params ? params.split(/,\s*(?=\w+:)/).find((p) => !named.has(p.split(":")[0].trim())) : undefined;
      const body = bodyParam ? (/:\s*Option</.test(bodyParam) ? `${bodyParam.split(":")[0].trim()}.as_ref()` : `Some(&${bodyParam.split(":")[0].trim()})`) : "None::<&()>";
      structs += `${docs}    pub async fn ${fn}(&self${typedParams ? ", " + typedParams : ""}) -> Result<Vec<u8>, crate::apis::Error<crate::apis::${module}::${errorType}>> {\n        self.0.download(reqwest::Method::${download.method}, &${path}, &[${query}], ${body}).await\n    }\n\n`;
    } else {
      structs += `${docs}    pub async fn ${fn}(&self${typedParams ? ", " + typedParams : ""}) -> ${typed.trim()} {\n        crate::apis::${module}::${fn}(&self.0.config${args.length ? ", " + args.join(", ") : ""}).await\n    }\n\n`;
    }
    count++;
  }
  structs = structs.trimEnd() + "\n}\n\n";
  accessors += `    /// ${name} operations.\n    pub fn ${area}(&self) -> ${name}<'_> {\n        ${name}(self)\n    }\n\n`;
}

const out = `// Generated by scripts/generate-resources.mjs from src/apis - do not edit.
use crate::Client;

impl Client {
${accessors.trimEnd()}
}

${structs.trimEnd()}
`;
writeFileSync(resolve(root, "src/resources.rs"), out);
console.log(`src/resources.rs: ${count} operations`);
